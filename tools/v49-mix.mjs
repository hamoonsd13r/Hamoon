fx("sfx/impact/metallic", wd(15, "انداخت") + 0.45, 0.3);
fx("sfx/pop/pop-2", wd(16, "سیم‌کارتِ"), 0.35);
fx("sfx/glitch/static", wd(18, "خش‌خش"), 0.45);
fx("sfx/glitch/static", wd(18, "خش‌خش") + 0.5, 0.35);
fx("sfx/impact/wood-hit-01-2", wd(20, "در"), 0.6);
fx("sfx/impact/wood-hit-01-2", wd(20, "در") + 0.3, 0.6);
fx("sfx/foley/cloth-3", wd(21, "برداشت"), 0.4);
fx("sfx/door/open", wd(22, "ولی"), 0.5);
fx("sfx/impact/metal-heavy-002", wd(23, "زمین"), 0.4);
fx("sfx/foley/cloth-2", wd(24, "درآورد"), 0.45);
[0, 1, 2, 3, 4, 5].forEach((i) => fx("sfx/footsteps/concrete-00" + (i % 2), S(25) + 0.2 + i * 0.4, 0.25));
fx("sfx/notification/like-tap", S(26) + 0.1, 0.3);
fx("sfx/riser/downlifter-dark", wd(26, "خیالیه"), 0.3);
fx("sfx/whoosh/soft-short", wd(27, "بی‌خبر") - 0.2, 0.3);
fx("sfx/impact/soft-thump", S(29), 0.35);
const M = (f, at, to, from = 0, fadeIn = 0.8, fadeOut = 2, gain = 0.1) => ({ file: "public/audio/music/" + f + ".mp3", at, from, to: from + (to - at), fadeIn, fadeOut, gain });
const music = [M("dark/game-over-4", 0, wd(22, "ولی") + 0.3, 0, 0.2, 1.2, 0.045), M("sad/mixed-signals", wd(22, "ولی") - 0.4, LEN, 0, 1.2, 2.5, 0.045)];
fs.writeFileSync("videos/49/mix.json", JSON.stringify({ length: LEN, voice: "public/v49/vo.wav", music, sfx }, null, 1));
