fx("sfx/impact/soft-thump", wd(11, "شناخت"), 0.35);
fx("sfx/paper/slide", wd(13, "گزارشش"), 0.4);
fx("sfx/impact/punchy-short", wd(13, "گزارشش") + 0.35, 0.3);
fx("sfx/whoosh/soft-short", S(14) - 0.05, 0.25);
