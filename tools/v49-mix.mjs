import fs from "node:fs";
const V = JSON.parse(fs.readFileSync("src/v49/vo.json", "utf8"));
const bare = (x) => x.replace(/[،.؟!?:«»]/g, "");
const S = (n) => V.segs.find((s) => s.n === n).start;
const wd = (l, w, occ = 1) => { const ws = V.words.filter((x) => x.line === l); const h = ws.filter((x) => bare(x.w) === w)[occ - 1] ?? ws.filter((x) => bare(x.w).includes(w))[occ - 1]; if (!h) throw new Error(l + " " + w); return h.s; };
const LEN = +(V.total + 1.6).toFixed(2), K = 0.32, sfx = [];
const fx = (id, at, vol = 0.4) => sfx.push({ id, at: +at.toFixed(3), vol: +(vol * K).toFixed(3) });
const fl = (file, at, vol = 0.4, peak = 0.05) => sfx.push({ file, at: +at.toFixed(3), vol: +(vol * K).toFixed(3), peak });
fx("sfx/impact/cinematic-heavy", 0.1, 0.45);
fx("sfx/impact/punchy-short", wd(2, "چمدونِ"), 0.3);
fl("public/v46/sfx/jet-1.mp3", wd(2, "پرواز") + 0.3, 0.35, 0.8);
fx("sfx/notification/notify-message", S(4) + 0.1, 0.35);
fx("sfx/ui/click-crisp", wd(4, "حاج‌آقا"), 0.3);
fx("sfx/whoosh/soft-short", wd(4, "تهران") - 0.05, 0.25);
fx("sfx/ui/toggle-off", wd(5, "خاموش") + 0.03, 0.55);
fx("sfx/whoosh/soft-short", S(6) - 0.05, 0.25);
